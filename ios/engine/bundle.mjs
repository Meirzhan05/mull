// Bundles Wonder's shared ES modules into classic scripts for iOS JavaScriptCore.
//
// JSContext evaluates scripts, not ES modules, so each module becomes a function in a small
// registry: `import {a, b as c} from './x.js'` -> `const {a, b: c} = __require('<path>')` and
// `export function f` / `export const x` / `export {a, b}` -> live getters on the module's
// exports object. Module bodies are otherwise copied byte for byte: the learning catalog builds
// its sandbox prelude from `fn.toString()`, so function sources must not change.
//
//   node ios/engine/bundle.mjs            write ios/Wonder/Engine/JS/*.js
//   node ios/engine/bundle.mjs --check    exit 1 if a written bundle is out of date

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const outDir = path.join(repo, 'ios/Wonder/Engine/JS');

export const BUNDLES = {
  // One per DIL surface (its own JSContext, like the web's one Web Worker per message).
  'wonder-engine.js': path.join(here, 'engine-entry.js'),
  // The app core: stream parser, deck/FSRS, practice grading, progress, steering helpers.
  'wonder-core.js': path.join(here, 'core-entry.js'),
};

const IMPORT_RE = /^import\s+(\{[^}]*\}|\*\s+as\s+\w+|\w+)\s+from\s+['"]([^'"]+)['"];?([ \t]*\/\/[^\n]*)?[ \t]*$/gm;
const BARE_IMPORT_RE = /^import\s+['"]([^'"]+)['"];?([ \t]*\/\/[^\n]*)?[ \t]*$/gm;

function rel(file) { return path.relative(repo, file).split(path.sep).join('/'); }

function transform(file, src, resolve) {
  const exportNames = []; // [exported, local]
  const deps = [];
  let body = src.replace(IMPORT_RE, (_, what, spec, comment = '') => {
    const dep = resolve(file, spec);
    deps.push(dep);
    const req = `__require(${JSON.stringify(rel(dep))})`;
    if (what.startsWith('*')) return `const ${what.replace(/^\*\s+as\s+/, '')} = ${req};${comment || ''}`;
    if (!what.startsWith('{')) throw new Error(`${rel(file)}: default imports are not supported (${what})`);
    const names = what.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean)
      .map((s) => { const m = /^(\w+)(?:\s+as\s+(\w+))?$/.exec(s); if (!m) throw new Error(`${rel(file)}: bad import ${s}`); return m[2] ? `${m[1]}: ${m[2]}` : m[1]; });
    return `const { ${names.join(', ')} } = ${req};${comment || ''}`;
  });
  body = body.replace(BARE_IMPORT_RE, (_, spec, comment = '') => { const dep = resolve(file, spec); deps.push(dep); return `__require(${JSON.stringify(rel(dep))});${comment || ''}`; });
  body = body.replace(/^export\s+((?:async\s+)?function\*?|class|const|let|var)\s+(\w+)/gm, (_, kw, name) => { exportNames.push([name, name]); return `${kw} ${name}`; });
  body = body.replace(/^export\s+\{([^}]*)\};?[ \t]*$/gm, (_, list) => {
    for (const s of list.split(',').map((x) => x.trim()).filter(Boolean)) {
      const m = /^(\w+)(?:\s+as\s+(\w+))?$/.exec(s);
      if (!m) throw new Error(`${rel(file)}: bad export ${s}`);
      exportNames.push([m[2] || m[1], m[1]]);
    }
    return '';
  });
  if (/^\s*export\s/m.test(body)) throw new Error(`${rel(file)}: unsupported export form`);
  if (/\bimport\s*\(|import\.meta/.test(body)) throw new Error(`${rel(file)}: dynamic import / import.meta are not supported`);
  const getters = exportNames.map(([ex, local]) => `  ${JSON.stringify(ex)}: { enumerable: true, get: () => ${local} },`).join('\n');
  return { deps, code: `Object.defineProperties(exports, {\n${getters}\n});\n${body}` };
}

export function bundle(entry, name) {
  const modules = new Map(); // abs path -> code
  const order = [];
  const resolve = (from, spec) => {
    if (!spec.startsWith('.')) throw new Error(`${rel(from)}: only relative imports can be bundled (${spec})`);
    return path.resolve(path.dirname(from), spec);
  };
  const visit = (file, stack = []) => {
    if (modules.has(file)) return;
    if (stack.includes(file)) throw new Error(`import cycle: ${[...stack, file].map(rel).join(' -> ')}`);
    const { deps, code } = transform(file, fs.readFileSync(file, 'utf8'), resolve);
    for (const d of deps) visit(d, [...stack, file]);
    modules.set(file, code);
    order.push(file);
  };
  visit(entry);
  const parts = order.map((f) => `__define(${JSON.stringify(rel(f))}, function (exports, __require) {\n${modules.get(f)}\n});`);
  return `// GENERATED by ios/engine/bundle.mjs from ${order.length} modules. Do not edit.
// Sources: ${order.map(rel).join(', ')}
(function () {
'use strict';
const __defs = new Map();
const __cache = new Map();
function __define(id, fn) { __defs.set(id, fn); }
function __require(id) {
  if (__cache.has(id)) return __cache.get(id);
  const fn = __defs.get(id);
  if (!fn) throw new Error('module not bundled: ' + id);
  const exports = {};
  __cache.set(id, exports);
  fn(exports, __require);
  return exports;
}
${parts.join('\n')}
__require(${JSON.stringify(rel(entry))});
})();
//# sourceURL=${name}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  fs.mkdirSync(outDir, { recursive: true });
  for (const [name, entry] of Object.entries(BUNDLES)) {
    const out = path.join(outDir, name);
    const code = bundle(entry, name);
    const old = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
    if (check) {
      if (old !== code) { console.error(`${rel(out)} is out of date: run node ios/engine/bundle.mjs`); stale++; }
    } else if (old !== code) {
      fs.writeFileSync(out, code);
      console.log(`wrote ${rel(out)} (${(code.length / 1024).toFixed(1)} KB)`);
    } else console.log(`${rel(out)} is up to date`);
  }
  process.exit(stale ? 1 : 0);
}
