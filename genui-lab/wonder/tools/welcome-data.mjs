// Builds the landing page's data (public/welcome/js/data.js) from recorded NDJSON fixtures: the
// replayed lesson (default claude-lesson-rome.ndjson) and the Teacher turn on Page 5.
//   npm run welcome:data [-- <lesson-fixture.ndjson>]
import fs from 'node:fs';
const FIX = new URL('../test/fixtures/', import.meta.url);
const read = (f) => fs.readFileSync(new URL(f, FIX), 'utf8').trim().split('\n').map((l) => JSON.parse(l));

// ---- the lesson stream: one event per record, in order ----
const [lessonFile = 'claude-lesson-rome.ndjson'] = process.argv.slice(2);
const L = read(lessonFile);
const events = [];
let sources = {};
for (const r of L) {
  if (r.type === 'content') {
    if (r.mode === 'append') events.push(['a', r.markdown || '']);
    else events.push(['r', r.markdown || '']);
    const cr = r.dil?.appData?.opGenui?.componentResults;
    if (cr) for (const v of Object.values(cr)) for (const it of v.state?.items || []) {
      sources[it.ref] = { n: it.index, domain: it.domain, title: it.title, url: it.url };
    }
  } else if (r.type === 'reasoning') events.push(['s', r.status.text]);
  else if (r.type === 'control' && r.detail.kind === 'steering-status') events.push(['steer', r.detail.instruction]);
  else if (r.type === 'control' && r.detail.kind === 'message-stream-complete') events.push(['done']);
}
const records = L.length;

// ---- the Teacher turn ----
const T = read('claude-teacher-statistics.ndjson');
let md = '';
let results = {};
const status = [];
for (const r of T) {
  if (r.type === 'content') {
    if (r.mode === 'append') md += r.markdown || ''; else if (r.markdown != null) md = r.markdown;
    const cr = r.dil?.appData?.opGenui?.componentResults; if (cr) results = cr;
  }
  if (r.type === 'reasoning') status.push(r.status.text);
}
const cards = Object.values(results).map((v) => v.state);
const teacher = {
  prompt: 'I want to get good at statistics in a week, I already know basic algebra',
  status: [...new Set(status)],
  memory: cards.filter((c) => c.kind === 'memory').map((c) => ({ fact: c.item.fact, kind: c.item.kind })),
  plan: cards.find((c) => c.kind === 'plan'),
  approval: cards.find((c) => c.kind === 'approval'),
  reply: md.split('\n\n').filter((p) => p && !p.startsWith('<')).slice(0, 2),
};

const out = `// Generated by tools/welcome-data.mjs (npm run welcome:data) from test/fixtures. Do not edit.
// The lesson stream: ${records} NDJSON records from claude-opus-5-5 (${lessonFile}).
export const STREAM = ${JSON.stringify(events)};
export const STREAM_RECORDS = ${records};
export const SOURCES = ${JSON.stringify(sources)};
export const TEACHER = ${JSON.stringify(teacher)};
`;
fs.writeFileSync(new URL('../public/welcome/js/data.js', import.meta.url), out);
console.log('events', events.length, 'sources', Object.keys(sources).length, 'bytes', out.length);
